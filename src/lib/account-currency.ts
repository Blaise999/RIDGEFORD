/** Currency of the underlying customer ledger. One account, one ledger currency. */
export type AccountCurrency = "EUR" | "USD";
export const ACCOUNT_CURRENCIES: AccountCurrency[] = ["EUR", "USD"];

export function accountCurrency(value: unknown): AccountCurrency {
  return value === "USD" ? "USD" : "EUR";
}

export function isAccountCurrency(value: unknown): value is AccountCurrency {
  return value === "USD" || value === "EUR";
}

export function currencySymbol(value: unknown): string {
  return accountCurrency(value) === "USD" ? "$" : "€";
}

export function bankIdentifierLabel(value: unknown): string {
  return accountCurrency(value) === "USD" ? "U.S. account number" : "IBAN";
}

export function accountIdentifier(user: { currency?: unknown; iban?: string | null; account_number?: string | null }): string {
  if (accountCurrency(user.currency) === "USD") return user.account_number || "Awaiting bank provisioning";
  return user.iban || "Pending approval";
}

/** US routing is institution-issued and may not be generated by the application. */
export function validAba(value: string): boolean {
  if (!/^\d{9}$/.test(value)) return false;
  const a = [...value].map(Number);
  return ((3 * (a[0] + a[3] + a[6]) + 7 * (a[1] + a[4] + a[7]) + a[2] + a[5] + a[8]) % 10) === 0;
}
export function validSwift(value: string): boolean {
  return /^[A-Z]{6}[A-Z0-9]{2}([A-Z0-9]{3})?$/.test(value.toUpperCase());
}
